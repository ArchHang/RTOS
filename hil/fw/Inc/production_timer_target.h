#ifndef F446_RTOS_HIL_FW_INC_PRODUCTION_TIMER_TARGET_H_
#define F446_RTOS_HIL_FW_INC_PRODUCTION_TIMER_TARGET_H_

#include "hil_target.h"

#if defined(STM32H743xx)
#define PRODUCTION_TIMER_APB_ENABLE (RCC->APB1LENR)
#define PRODUCTION_TIMER_TIM2_ENABLE RCC_APB1LENR_TIM2EN
#define PRODUCTION_TIMER_TIM6_ENABLE RCC_APB1LENR_TIM6EN
#define PRODUCTION_TIMER_TIM7_ENABLE RCC_APB1LENR_TIM7EN
#define PRODUCTION_TIMER_DAC_ENABLE RCC_APB1LENR_DAC12EN
#define PRODUCTION_TIMER_DAC DAC1
#define PRODUCTION_TIMER_CLOCK_HZ (240000000U)
/* Board profile: 480 MHz core, 240 MHz HCLK, 120 MHz PCLK1, TIMPRE=0. */
#define PRODUCTION_TIMER_PROFILE_VALID() \
    ((SystemCoreClock == 480000000U) && \
     ((RCC->D1CFGR & RCC_D1CFGR_HPRE) == RCC_D1CFGR_HPRE_DIV2) && \
     ((RCC->D2CFGR & RCC_D2CFGR_D2PPRE1) == RCC_D2CFGR_D2PPRE1_DIV2) && \
     ((RCC->CFGR & RCC_CFGR_TIMPRE) == 0U))
#else
#include "stm32f4xx_hal.h"

#define PRODUCTION_TIMER_APB_ENABLE (RCC->APB1ENR)
#define PRODUCTION_TIMER_TIM2_ENABLE RCC_APB1ENR_TIM2EN
#define PRODUCTION_TIMER_TIM6_ENABLE RCC_APB1ENR_TIM6EN
#define PRODUCTION_TIMER_TIM7_ENABLE RCC_APB1ENR_TIM7EN
#define PRODUCTION_TIMER_DAC_ENABLE RCC_APB1ENR_DACEN
#define PRODUCTION_TIMER_DAC DAC
#define PRODUCTION_TIMER_CLOCK_HZ (84000000U)
/* Board profile: 168 MHz HCLK, 42 MHz PCLK1, TIMPRE=0. */
#define PRODUCTION_TIMER_PROFILE_VALID() \
    ((SystemCoreClock == 168000000U) && \
     (HAL_RCC_GetPCLK1Freq() == (PRODUCTION_TIMER_CLOCK_HZ / 2U)) && \
     ((RCC->CFGR & RCC_CFGR_PPRE1) == RCC_CFGR_PPRE1_DIV4) && \
     ((RCC->DCKCFGR & RCC_DCKCFGR_TIMPRE) == 0U))
#endif

#endif /* F446_RTOS_HIL_FW_INC_PRODUCTION_TIMER_TARGET_H_ */
